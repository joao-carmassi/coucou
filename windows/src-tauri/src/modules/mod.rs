// modules) needs nothing: the host treats it as on/off by setting only.

use crate::core::host::{Handler, Module, ModuleInfo};

// Generated by build.rs from src/modules/*/manifest.json (order, ids, requires, group; devOnly = debug builds only),
// plus ESSENTIAL: the ids with `"essential": true`, the only ones left on in safe mode (core/safe_mode.rs).
include!(concat!(env!("OUT_DIR"), "/catalog.rs"));
// Generated by build.rs from the folders holding a mod.rs: the `pub mod`s, registry() and handlers().
include!(concat!(env!("OUT_DIR"), "/modules.rs"));

#[cfg(test)]
mod tests {
    use crate::core::host::Module;

    #[test]
    fn migrate_installed_baseline_and_legacy() {
        use crate::core::settings::{fill_defaults, Settings};
        let run = |json: &str| {
            let mut s: Settings = serde_json::from_str(json).unwrap();
            // Static calls: a `dyn Module` vtable would link tauri into the test exe (see below).
            let mut changed = super::voice::Voice.migrate(&mut s);
            for short in ["github", "vercel", "stripe", "n8n", "resend", "calcom", "notion"] {
                changed |= super::integrations::Provider { short }.migrate(&mut s);
            }
            (fill_defaults(super::CATALOG, &mut s) | changed, s)
        };
        let (changed, s) = run(r#"{"autostart":true,"model":"x","activeIntegrations":[],"voiceEnabled":true}"#);
        assert!(changed);
        let on: Vec<_> = s.modules_enabled.iter().filter(|(_, v)| **v).map(|(k, _)| k.as_str()).collect();
        assert_eq!(on, ["board", "claude", "media", "upload", "voice"]);
        assert_eq!(s.extra["model"], "x", "unknown keys survive");
        let (changed, _) = run(&serde_json::to_string(&s).unwrap());
        assert!(!changed, "a migrated file is stable");
    }

    // Calling registry() would link all of tauri into the test exe, which cannot start without a
    // manifest (see core/host.rs tests): check the id statically and the entry in the source.
    // The manifests are the single source; Rust (build.rs) and TS (import.meta.glob) both read them.
    #[test]
    fn catalog_matches_manifests() {
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/modules");
        let mut want: Vec<serde_json::Value> = Vec::new();
        for e in std::fs::read_dir(dir).unwrap() {
            let Ok(t) = std::fs::read_to_string(e.unwrap().path().join("manifest.json")) else { continue };
            match serde_json::from_str(&t).unwrap() {
                serde_json::Value::Array(v) => want.extend(v),
                v => want.push(v),
            }
        }
        // devOnly modules are in the catalog of debug builds only.
        want.retain(|m| cfg!(debug_assertions) || m["devOnly"] != true);
        want.sort_by(|a, b| (a["order"].as_i64(), a["id"].as_str()).cmp(&(b["order"].as_i64(), b["id"].as_str())));
        assert_eq!(want.len(), super::CATALOG.len());
        for (w, c) in want.iter().zip(super::CATALOG) {
            assert_eq!(w["id"], c.id);
            assert_eq!(w["label"], c.label);
            assert_eq!(w["default"], c.default_enabled);
            assert_eq!(w["group"].as_str(), c.group);
            let req: Vec<&str> = w["requires"].as_array().map_or(vec![], |a| a.iter().map(|r| r.as_str().unwrap()).collect());
            assert_eq!(req, c.requires, "{}", c.id);
        }
        for (i, c) in super::CATALOG.iter().enumerate() {
            assert!(c.requires.iter().all(|r| super::CATALOG[..i].iter().any(|p| p.id == *r)), "{} requires a later module", c.id);
        }
    }

    #[test]
    fn claude_is_registered() {
        assert_eq!(super::claude::Claude.id(), "claude");
        assert!(super::CATALOG.iter().any(|m| m.id == "claude"));
        let generated = std::fs::read_to_string(concat!(env!("OUT_DIR"), "/modules.rs")).unwrap();
        assert!(generated.contains("pub mod claude;"), "build.rs lost the claude folder");
    }
}
